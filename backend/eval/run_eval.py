#!/usr/bin/env python3
"""Blind eval: run every packet in data/packets through the pipeline, then compare the recommendation with
IHH's real decisions. eval/decisions.json is read ONLY here, after all extraction is done, never in a prompt.

Usage: python3 backend/eval/run_eval.py [--packets R01,R05] [--mock]
Writes data/runs/eval.md and prints the table."""
from __future__ import annotations
import argparse, json, pathlib, sys, time
ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--packets", default=None)
    ap.add_argument("--mock", action="store_true")
    ap.add_argument("--provider", default="ihh")
    args = ap.parse_args()
    if args.mock:
        import os; os.environ["SST_MOCK"] = "1"
    from backend import sstlib, store
    from backend.pipeline import ingest, page_index, extract, gaps
    store.init_db()
    wanted = args.packets.split(",") if args.packets else None
    pdfs = sorted(p for p in (ROOT / "data" / "packets").glob("R*.pdf") if not wanted or p.stem in wanted)
    if not pdfs:
        print("no packets in data/packets/"); return
    results = []
    for pdf in pdfs:
        t = time.time()
        sst = sstlib.new_sst(f"EVAL-{pdf.stem}")
        rid = sst["meta"]["referral_id"]
        sst["meta"]["packet"]["source_file"] = str(pdf)
        sst["meta"]["parties"]["providers"] = [{"provider_id": args.provider, "name": "Illumination Health + Home", "status": "reviewing", "updated_at": sstlib.now_iso()}]
        if store.get_referral(rid) is None:
            store.create_referral(sst, str(pdf), f"eval {pdf.stem}")
        try:
            total = ingest.render(rid, str(pdf))
            page_index.index_pages(sst, rid, total)
            report = extract.extract(sst, rid)
            el = gaps.run_all(sst, args.provider)
            store.save_sst(rid, sst, "system", "eval run")
            err = "; ".join(f"{k}: {v}" for k, v in report.items() if v not in ("ok",) and not v.startswith("mock")) or None
            results.append({"packet": pdf.stem, "pages": total, "rec": el["recommendation"], "hard_stops": el["hard_stops"],
                            "cant_tell": len(el["scores"]["components"]["rule_coverage"]["cant_tell_rule_ids"]),
                            "readiness": el["scores"]["readiness"], "secs": round(time.time() - t), "error": err})
        except Exception as e:
            results.append({"packet": pdf.stem, "pages": None, "rec": None, "hard_stops": [], "cant_tell": None, "readiness": None, "secs": round(time.time() - t), "error": f"{type(e).__name__}: {str(e)[:120]}"})
        print(f"{pdf.stem}: {results[-1]['rec']} ({results[-1]['secs']}s)", flush=True)

    # Only now: IHH's decisions, for scoring.
    decisions = {d["packet_id"]: d["decision"] for d in json.loads((ROOT / "eval" / "decisions.json").read_text())["packets"]}
    agree = 0; rows = []
    for r in results:
        ihh = decisions.get(r["packet"])
        ours = {"likely_eligible": "approve", "likely_ineligible": "deny"}.get(r["rec"], "request_information")
        match = "yes" if ours == ihh else ("partial" if ours == "request_information" else "NO")
        if match == "yes": agree += 1
        rows.append(f"| {r['packet']} | {r['pages'] or ''} | {r['rec'] or 'error'} | {', '.join(r['hard_stops'])} | {r['cant_tell'] if r['cant_tell'] is not None else ''} | {r['readiness'] if r['readiness'] is not None else ''} | {ihh} | {match} | {r['error'] or ''} |")
    table = ["| Packet | Pages | Our recommendation | Hard stops | Rules can't tell | Readiness | IHH decided | Agree | Errors |", "|---|---|---|---|---|---|---|---|---|"] + rows
    summary = f"\n{agree} of {len(results)} recommendations match IHH's decision outright; 'partial' means we asked for more information where IHH decided."
    out = "# Blind eval\n\nGenerated by `backend/eval/run_eval.py`. Decisions were loaded only after every extraction finished.\n\n" + "\n".join(table) + "\n" + summary + "\n"
    (ROOT / "data" / "runs").mkdir(parents=True, exist_ok=True)
    (ROOT / "data" / "runs" / "eval.md").write_text(out)
    print("\n" + out)


if __name__ == "__main__":
    main()
